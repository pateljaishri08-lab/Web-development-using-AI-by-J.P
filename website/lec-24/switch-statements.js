// example 2 print a message based on the day of the week

const day = 3;

switch (day) {
    case 1:
        console.log("Monday - Start of the week!");
        break;
    case 2:
        console.log("Tuesday - Keep going!");
        break;
    case 3:
        console.log("Wednesday - Halfway through the week!");
        break;
    case 4:
        console.log("Thursday - Almost there!");
        break;
    case 5:
        console.log("Friday - TGIF!");
        break;
    case 6:
        console.log("Saturday - Enjoy the weekend!");
        break;
    case 7:
        console.log("Sunday - Relax and prepare for the week!");
        break;
    default:
        console.log("Invalid day number");
}





